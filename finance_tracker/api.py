"""REST API for the web dashboard (Phase 4).

This file is the web version of cli.py: it turns HTTP requests into calls on
the same Store, PriceService, and reports functions, and returns JSON. None of
the business logic lives here.

Run it with `python main.py --web`, then open http://127.0.0.1:8000.
Interactive API docs (generated by FastAPI) are at http://127.0.0.1:8000/docs.

Endpoints
---------
GET    /api/profile                  your name (null for a new user)
POST   /api/profile                  create the profile
GET    /api/summary?month=           spent / income / net for one month
GET    /api/months                   months that have transactions (for pickers)
GET    /api/categories?kind=         category names, most used first
GET    /api/transactions?month=      transactions, newest first
POST   /api/transactions             add one
DELETE /api/transactions/{id}        delete one
GET    /api/transactions.csv         download everything as CSV
GET    /api/reports/categories       spending per category (optionally one month)
GET    /api/reports/monthly          last 12 months with how unusual each was
GET    /api/holdings                 your holdings
POST   /api/holdings                 add one
PATCH  /api/holdings/{id}            change quantity or value
DELETE /api/holdings/{id}            remove one
GET    /api/quotes/{symbol}          live price for a ticker (used to check symbols)
GET    /api/net-worth                value everything at live prices
GET    /api/net-worth/history        daily net-worth snapshots
"""

import csv
import io
import math
from datetime import date
from pathlib import Path
from typing import Any, Callable, Dict, Iterator, List, Optional, Union

from fastapi import Depends, FastAPI, HTTPException, Query, Response
from fastapi.staticfiles import StaticFiles
from pydantic import BaseModel, Field

from . import reports
from .models import (
    GOLD_SYMBOL,
    AssetType,
    Holding,
    Kind,
    Transaction,
    cents_to_plain,
    month_of,
    parse_date,
    parse_money,
    parse_month,
)
from .paths import FRONTEND_DIST, database_path
from .prices import PriceProvider, PriceService, PriceUnavailable, YahooPriceProvider
from .store import Store

# ------------------------------------------------------------ request bodies
# Pydantic checks the *shape* of incoming JSON (right fields, right types).
# The *meaning* (is this a real amount? a real date?) is checked by the same
# parse_* helpers and dataclasses the terminal app uses.


class ProfileIn(BaseModel):
    name: str = Field(min_length=1, max_length=80)


class TransactionIn(BaseModel):
    description: str = Field(max_length=200)
    amount: str = Field(description="Dollar amount as text, e.g. '4.50' or '$1,200'")
    category: str = Field(max_length=60)
    occurred_on: Optional[str] = Field(None, description="YYYY-MM-DD; blank means today")
    kind: Kind = Kind.EXPENSE


class HoldingIn(BaseModel):
    asset_type: AssetType
    name: Optional[str] = Field(None, max_length=80)
    symbol: Optional[str] = Field(None, max_length=20)
    quantity: Optional[float] = None
    value: Optional[str] = Field(None, description="Dollar value, for cash and other")


class HoldingUpdate(BaseModel):
    quantity: Optional[float] = None
    value: Optional[str] = None


# --------------------------------------------------------------------- app


def create_app(
    db_path: Union[str, Path],
    *,
    provider: Optional[PriceProvider] = None,
    today: Callable[[], date] = date.today,
    static_dir: Optional[Path] = FRONTEND_DIST,
) -> FastAPI:
    db_path = str(db_path)
    provider = provider or YahooPriceProvider()

    # Create/upgrade the database once up front, so simultaneous first
    # requests don't race to create the tables.
    Store(db_path).close()

    app = FastAPI(title="Finance Tracker API", version="1.0")

    def get_store() -> Iterator[Store]:
        """One database connection per request, always closed afterwards."""
        store = Store(db_path, check_same_thread=False)
        try:
            yield store
        finally:
            store.close()

    def price_service(store: Store) -> PriceService:
        return PriceService(store, provider)

    # ---------------------------------------------------------- profile

    @app.get("/api/profile")
    def get_profile(store: Store = Depends(get_store)) -> Dict[str, Any]:
        return {"name": store.profile_name()}

    @app.post("/api/profile", status_code=201)
    def create_profile(body: ProfileIn, store: Store = Depends(get_store)) -> Dict[str, Any]:
        name = body.name.strip()
        if not name:
            raise HTTPException(400, "name can't be blank")
        if store.profile_name() is not None:
            raise HTTPException(409, "a profile already exists")
        store.create_profile(name)
        return {"name": name}

    # ------------------------------------------------- transactions

    @app.get("/api/summary")
    def summary(month: Optional[str] = None, store: Store = Depends(get_store)) -> Dict[str, Any]:
        month = _month_or_400(month) or month_of(today())
        spent = sum(c for _, c in store.totals_by_category(Kind.EXPENSE, month=month))
        income = sum(c for _, c in store.totals_by_category(Kind.INCOME, month=month))
        return {
            "month": month,
            "current_month": month_of(today()),
            "spent_cents": spent,
            "income_cents": income,
            "net_cents": income - spent,
            "transaction_count": store.transaction_count(),
        }

    @app.get("/api/months")
    def months(store: Store = Depends(get_store)) -> List[str]:
        found = {m for m, _ in store.totals_by_month(Kind.EXPENSE)}
        found |= {m for m, _ in store.totals_by_month(Kind.INCOME)}
        found.add(month_of(today()))
        return sorted(found, reverse=True)

    @app.get("/api/categories")
    def categories(kind: Kind = Kind.EXPENSE, store: Store = Depends(get_store)) -> List[str]:
        return store.categories(kind)

    @app.get("/api/transactions")
    def list_transactions(
        month: Optional[str] = None,
        limit: int = Query(200, ge=1, le=5000),
        store: Store = Depends(get_store),
    ) -> Dict[str, Any]:
        rows = store.transactions(limit=limit, month=_month_or_400(month))
        return {"items": [_tx_json(tx) for tx in rows], "total": store.transaction_count()}

    @app.post("/api/transactions", status_code=201)
    def add_transaction(body: TransactionIn, store: Store = Depends(get_store)) -> Dict[str, Any]:
        try:
            cents = parse_money(body.amount)
            if cents <= 0:
                raise ValueError("amount must be greater than zero")
            tx = Transaction(
                description=body.description.strip(),
                amount_cents=cents,
                category=body.category,
                occurred_on=parse_date(body.occurred_on or "", today=today()),
                kind=body.kind,
            )
        except ValueError as exc:
            raise HTTPException(400, str(exc)) from None
        tx_id = store.add_transaction(tx)
        return _tx_json(store.get_transaction(tx_id))

    @app.delete("/api/transactions/{tx_id}", status_code=204)
    def delete_transaction(tx_id: int, store: Store = Depends(get_store)) -> Response:
        if not store.delete_transaction(tx_id):
            raise HTTPException(404, f"no transaction with id {tx_id}")
        return Response(status_code=204)

    @app.get("/api/transactions.csv")
    def export_csv(store: Store = Depends(get_store)) -> Response:
        buffer = io.StringIO()
        writer = csv.writer(buffer)
        writer.writerow(["id", "date", "kind", "category", "description", "amount"])
        for tx in reversed(store.transactions()):
            writer.writerow([
                tx.id, tx.occurred_on.isoformat(), tx.kind.value,
                tx.category, tx.description, cents_to_plain(tx.amount_cents),
            ])
        filename = f"transactions-{today().isoformat()}.csv"
        return Response(
            buffer.getvalue(),
            media_type="text/csv",
            headers={"Content-Disposition": f'attachment; filename="{filename}"'},
        )

    # ------------------------------------------------------ reports

    @app.get("/api/reports/categories")
    def category_report(
        month: Optional[str] = None,
        kind: Kind = Kind.EXPENSE,
        store: Store = Depends(get_store),
    ) -> Dict[str, Any]:
        month = _month_or_400(month)
        rows = store.totals_by_category(kind, month=month)
        total = sum(c for _, c in rows)
        return {
            "month": month,
            "kind": kind.value,
            "total_cents": total,
            "items": [
                {"category": name, "total_cents": cents, "share": cents / total if total else 0}
                for name, cents in rows
            ],
        }

    @app.get("/api/reports/monthly")
    def monthly_report(store: Store = Depends(get_store)) -> Dict[str, Any]:
        report = reports.monthly_report(
            store.totals_by_month(Kind.EXPENSE), current_month=month_of(today())
        )
        return {
            "mean_cents": report.mean_cents,
            "stdev_cents": report.stdev_cents,
            "months": [
                {
                    "month": row.month,
                    "total_cents": row.total_cents,
                    "z_score": row.z_score,
                    "label": row.label,
                    "in_progress": row.in_progress,
                }
                for row in report.rows
            ],
        }

    # ----------------------------------------------------- holdings

    @app.get("/api/holdings")
    def list_holdings(store: Store = Depends(get_store)) -> List[Dict[str, Any]]:
        return [_holding_json(h) for h in store.holdings()]

    @app.post("/api/holdings", status_code=201)
    def add_holding(body: HoldingIn, store: Store = Depends(get_store)) -> Dict[str, Any]:
        try:
            holding = _build_holding(body)
        except ValueError as exc:
            raise HTTPException(400, str(exc)) from None
        holding_id = store.add_holding(holding)
        return _holding_json(store.get_holding(holding_id))

    @app.patch("/api/holdings/{holding_id}")
    def update_holding(
        holding_id: int, body: HoldingUpdate, store: Store = Depends(get_store)
    ) -> Dict[str, Any]:
        holding = store.get_holding(holding_id)
        if holding is None:
            raise HTTPException(404, f"no holding with id {holding_id}")
        try:
            if holding.asset_type.is_market_priced:
                store.update_holding(holding_id, quantity=_quantity(body.quantity))
            else:
                store.update_holding(holding_id, manual_value_cents=_value(body.value))
        except ValueError as exc:
            raise HTTPException(400, str(exc)) from None
        return _holding_json(store.get_holding(holding_id))

    @app.delete("/api/holdings/{holding_id}", status_code=204)
    def remove_holding(holding_id: int, store: Store = Depends(get_store)) -> Response:
        if not store.remove_holding(holding_id):
            raise HTTPException(404, f"no holding with id {holding_id}")
        return Response(status_code=204)

    @app.get("/api/quotes/{symbol}")
    def quote(symbol: str, store: Store = Depends(get_store)) -> Dict[str, Any]:
        try:
            q = price_service(store).quote(symbol)
        except PriceUnavailable as exc:
            raise HTTPException(404, str(exc)) from None
        return {
            "symbol": q.symbol,
            "price": q.price,
            "currency": q.currency,
            "fetched_at": q.fetched_at.isoformat(),
            "stale": q.stale,
        }

    # ---------------------------------------------------- net worth

    @app.get("/api/net-worth")
    def net_worth(store: Store = Depends(get_store)) -> Dict[str, Any]:
        """Value every holding at live prices.

        Also records today's snapshot for the history chart. That's a write
        inside a GET, but it's idempotent -- checking twice in one day just
        replaces the day's number -- and only complete valuations are kept.
        """
        holdings = store.holdings()
        report = reports.value_holdings(holdings, price_service(store).quote)
        previous = None
        if holdings and report.complete:
            previous = store.latest_snapshot_before(today())
            store.record_net_worth(today(), report.total_cents)

        by_type: Dict[str, int] = {}
        for line in report.lines:
            if line.value_cents is not None:
                key = line.holding.asset_type.value
                by_type[key] = by_type.get(key, 0) + line.value_cents

        return {
            "total_cents": report.total_cents,
            "complete": report.complete,
            "change_cents": report.total_cents - previous[1] if previous else None,
            "change_since": previous[0].isoformat() if previous else None,
            "by_type": [
                {"asset_type": t.value, "value_cents": by_type[t.value]}
                for t in AssetType if t.value in by_type  # fixed order, so colors stay put
            ],
            "lines": [
                {
                    **_holding_json(line.holding),
                    "value_cents": line.value_cents,
                    "unit_price": line.unit_price,
                    "note": line.note,
                }
                for line in report.lines
            ],
        }

    @app.get("/api/net-worth/history")
    def net_worth_history(store: Store = Depends(get_store)) -> List[Dict[str, Any]]:
        return [
            {"date": day.isoformat(), "total_cents": cents}
            for day, cents in store.net_worth_history()
        ]

    # -------------------------------------------------- the website
    # Mounted last so every /api route above takes priority.
    if static_dir is not None and Path(static_dir).is_dir():
        app.mount("/", StaticFiles(directory=str(static_dir), html=True), name="frontend")

    return app


def create_default_app() -> FastAPI:
    """Factory for `uvicorn finance_tracker.api:create_default_app --factory --reload`."""
    return create_app(database_path())


def serve(db_path: Union[str, Path], *, port: int = 8000) -> None:
    import uvicorn

    has_site = FRONTEND_DIST.is_dir()
    print(f"Finance tracker running at http://127.0.0.1:{port}")
    if not has_site:
        print("  (The website isn't built yet: run `npm run build` in frontend/. The API works now.)")
    print(f"  API docs: http://127.0.0.1:{port}/docs   Stop with Ctrl-C.")
    # 127.0.0.1 = only this computer can connect. Your financial data is never
    # exposed to other devices on your network.
    uvicorn.run(create_app(db_path), host="127.0.0.1", port=port, log_level="warning")


# ------------------------------------------------------------------ helpers


def _month_or_400(month: Optional[str]) -> Optional[str]:
    if not month:
        return None
    try:
        return parse_month(month)
    except ValueError as exc:
        raise HTTPException(400, str(exc)) from None


def _quantity(value: Optional[float]) -> float:
    if value is None or not math.isfinite(value) or value <= 0:
        raise ValueError("quantity must be greater than zero")
    return float(value)


def _value(value: Optional[str]) -> int:
    cents = parse_money(value or "")
    if cents < 0:
        raise ValueError("value can't be negative")
    return cents


def _build_holding(body: HoldingIn) -> Holding:
    if body.asset_type is AssetType.GOLD:
        return Holding(AssetType.GOLD, (body.name or "Gold").strip() or "Gold",
                       _quantity(body.quantity), symbol=GOLD_SYMBOL)
    if body.asset_type.is_market_priced:
        symbol = (body.symbol or "").strip().upper()
        if not symbol:
            raise ValueError("enter a symbol, e.g. AAPL")
        name = (body.name or "").strip() or symbol
        return Holding(body.asset_type, name, _quantity(body.quantity), symbol=symbol)
    return Holding(body.asset_type, (body.name or "").strip(), manual_value_cents=_value(body.value))


def _tx_json(tx: Transaction) -> Dict[str, Any]:
    return {
        "id": tx.id,
        "description": tx.description,
        "amount_cents": tx.amount_cents,
        "category": tx.category,
        "occurred_on": tx.occurred_on.isoformat(),
        "kind": tx.kind.value,
    }


def _holding_json(h: Holding) -> Dict[str, Any]:
    return {
        "id": h.id,
        "asset_type": h.asset_type.value,
        "name": h.name,
        "symbol": h.symbol,
        "quantity": h.quantity,
        "manual_value_cents": h.manual_value_cents,
    }
