def create_app(
    db_path: Union[str, Path],
    *,
    provider: Optional[PriceProvider] = None,
    today: Callable[[], date] = date.today,
    static_dir: Optional[Path] = FRONTEND_DIST,
    ai_client_factory: Callable[[str], Any] = OllamaClient,
) -> FastAPI:
    db_path = str(db_path)
    provider = provider or YahooPriceProvider()

    # Create/upgrade the database once up front, so simultaneous first
    # requests don't race to create the tables.
    Store(db_path).close()
    backup.secure_database(db_path)

    app = FastAPI(title="Finance Tracker API", version="1.0")
    last_backup_day = {"day": None}

    def daily_backup() -> None:
        """At most one check per calendar day, even if the server runs for weeks."""
        day = date.today()
        if last_backup_day["day"] != day:
            last_backup_day["day"] = day
            try:
                backup.make_backup(db_path)
            except (OSError, backup.BackupError, sqlite3.Error) as exc:
                print(f"Warning: daily backup failed: {exc}")

    daily_backup()

    def get_store() -> Iterator[Store]:
        """One database connection per request, always closed afterwards."""
        daily_backup()
        store = Store(db_path, check_same_thread=False)
        try:
            store.apply_recurring(today())
            yield store
        finally:
            store.close()

    def price_service(store: Store) -> PriceService:
        return PriceService(store, provider)

    # ------------------------------------------------------- passcode lock
    # Every /api/ request except /api/auth/... needs a signed-in session.
    # The website itself (HTML/JS/CSS) stays reachable so it can show the
    # lock screen, but it contains no data.

    def signed_in(request: Request, store: Store) -> bool:
        token = request.cookies.get(auth.COOKIE)
        return bool(token) and store.check_session(auth.token_hash(token), max_idle_days=auth.SESSION_DAYS)

    @app.middleware("http")
    async def require_passcode(request: Request, call_next):
        path = request.url.path
        if path.startswith("/api/") and not path.startswith("/api/auth/"):
            with Store(db_path, check_same_thread=False) as store:
                if not signed_in(request, store):
                    return JSONResponse({"detail": "locked"}, status_code=401)
        return await call_next(request)

    def start_session(request: Request, response: Response, store: Store) -> None:
        token = auth.new_session_token()
        store.add_session(auth.token_hash(token), request.headers.get("user-agent", ""))
        response.set_cookie(
            auth.COOKIE, token, max_age=auth.SESSION_DAYS * 86400,
            httponly=True,       # page scripts can't read it
            samesite="strict",   # other sites can't make requests with it
            path="/",
        )

    def check_guess(store: Store, code: str) -> None:
        """Verify a passcode guess, enforcing the lockout. Raises HTTPException if wrong."""
        now = datetime.now(timezone.utc)
        failures, locked_until = store.auth_failures()
        if locked_until and locked_until > now:
            wait = int((locked_until - now).total_seconds()) + 1
            raise HTTPException(429, f"Too many wrong tries. Try again in {wait} seconds.",
                                headers={"Retry-After": str(wait)})
        stored = store.passcode_hash()
        if stored and auth.verify_passcode(code, stored):
            store.set_auth_failures(0, None)
            return
        failures += 1
        lock = auth.lockout_seconds(failures)
        store.set_auth_failures(failures, now + timedelta(seconds=lock) if lock else None)
        left = max(auth.FREE_ATTEMPTS - failures, 0)
        message = "Wrong passcode."
        if lock:
            message += f" Locked for {lock} seconds."
        elif left <= 2:
            message += f" {left} {'try' if left == 1 else 'tries'} left before a short lockout."
        raise HTTPException(401, message)

    @app.get("/api/auth/status")
    def auth_status(request: Request) -> Dict[str, Any]:
        with Store(db_path, check_same_thread=False) as store:
            return {"passcode_set": store.passcode_hash() is not None, "signed_in": signed_in(request, store)}

    @app.post("/api/auth/setup")
    def auth_setup(body: PasscodeIn, request: Request, response: Response) -> Dict[str, Any]:
        """First run only: choose the passcode (and get signed in)."""
        try:
            code = auth.validate_passcode(body.passcode)
        except ValueError as exc:
            raise HTTPException(400, str(exc)) from None
        with Store(db_path, check_same_thread=False) as store:
            if store.passcode_hash() is not None:
                raise HTTPException(409, "A passcode is already set.")
            store.set_passcode_hash(auth.hash_passcode(code))
            start_session(request, response, store)
        return {"passcode_set": True, "signed_in": True}

    @app.post("/api/auth/login")
    def auth_login(body: PasscodeIn, request: Request, response: Response) -> Dict[str, Any]:
        with Store(db_path, check_same_thread=False) as store:
            if store.passcode_hash() is None:
                raise HTTPException(409, "No passcode has been set yet.")
            check_guess(store, body.passcode.strip())
            start_session(request, response, store)
        return {"passcode_set": True, "signed_in": True}

    @app.post("/api/auth/logout")
    def auth_logout(request: Request, response: Response) -> Dict[str, Any]:
        token = request.cookies.get(auth.COOKIE)
        if token:
            with Store(db_path, check_same_thread=False) as store:
                store.delete_session(auth.token_hash(token))
        response.delete_cookie(auth.COOKIE, path="/")
        return {"signed_in": False}

    @app.post("/api/auth/change")
    def auth_change(body: PasscodeChange, request: Request) -> Dict[str, Any]:
        """Change the passcode; every other signed-in device is signed out."""
        with Store(db_path, check_same_thread=False) as store:
            if not signed_in(request, store):
                raise HTTPException(401, "locked")
            try:
                new = auth.validate_passcode(body.new)
            except ValueError as exc:
                raise HTTPException(400, str(exc)) from None
            check_guess(store, body.current.strip())
            store.set_passcode_hash(auth.hash_passcode(new))
            others = store.delete_other_sessions(auth.token_hash(request.cookies[auth.COOKIE]))
        return {"changed": True, "signed_out_devices": others}

    # ---------------------------------------------------------- profile

    @app.get("/api/profile")
    def get_profile(store: Store = Depends(get_store)) -> Dict[str, Any]:
        return {"name": store.profile_name()}

    @app.post("/api/profile", status_code=201)
    def create_profile(body: ProfileIn, store: Store = Depends(get_store)) -> Dict[str, Any]:
        name = body.name.strip()
        if not name:
            raise HTTPException(400, "name can't be blank")
        if store.profile_name() is not None:
            raise HTTPException(409, "a profile already exists")
        store.create_profile(name)
        return {"name": name}

    @app.put("/api/profile")
    def rename_profile(body: ProfileIn, store: Store = Depends(get_store)) -> Dict[str, Any]:
        name = body.name.strip()
        if not name:
            raise HTTPException(400, "name can't be blank")
        if store.profile_name() is None:
            raise HTTPException(404, "no profile yet")
        store.rename_profile(name)
        return {"name": name}

