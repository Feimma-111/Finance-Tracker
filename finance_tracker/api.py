"""REST API for the web dashboard (Phase 4).

This file is the web version of cli.py: it turns HTTP requests into calls on
the same Store, PriceService, and reports functions, and returns JSON. None of
the business logic lives here.

Run it with `python main.py --web`, then open http://127.0.0.1:8000.
Interactive API docs (generated by FastAPI) are at http://127.0.0.1:8000/docs.

Endpoints
---------
Everything below except /api/auth/... needs a signed-in session (6-digit passcode).

GET    /api/auth/status              is a passcode set? is this browser signed in?
POST   /api/auth/setup               first run: choose the passcode
POST   /api/auth/login               sign in with the passcode
POST   /api/auth/logout              sign this browser out ("Lock")
POST   /api/auth/change              change the passcode (signs out other devices)
GET    /api/profile                  your name (null for a new user)
POST   /api/profile                  create the profile
GET    /api/summary?month=           spent / income / net for one month
GET    /api/months                   months that have transactions (for pickers)
GET    /api/categories?kind=         category names, most used first
GET    /api/categories/suggest?description=   the category you've used before for it
GET    /api/transactions?month=      transactions, newest first
POST   /api/transactions             add one
GET    /api/transactions/{id}        one transaction (+ how many share its description)
PATCH  /api/transactions/{id}        edit it (optionally recategorize matching ones)
POST   /api/transactions/{id}/recurring   make it the start of a recurring rule
DELETE /api/transactions/{id}        delete one
GET    /api/transactions.csv         download everything as CSV
GET    /api/backups                  automatic backups (made daily, and before imports)
POST   /api/backups                  back up now
GET    /api/backups/download         download a full copy of the database
POST   /api/import/preview           read a CSV and show what importing would do
POST   /api/import                   import a CSV's new transactions
GET    /api/reports/categories       spending per category (optionally one month)
GET    /api/reports/purchases?category=&month=   one category's purchases, grouped by description
GET    /api/reports/monthly          last 12 months with how unusual each was
GET    /api/reports/pace?month=      running total through a month vs the month before
GET    /api/holdings                 your holdings
POST   /api/holdings                 add one
PATCH  /api/holdings/{id}            change name, symbol, quantity or value
GET    /api/holdings/{id}/activity   an account's transactions and transfers / an investment's purchase
DELETE /api/holdings/{id}            remove one
GET    /api/quotes/{symbol}          live price for a ticker (used to check symbols)
GET    /api/net-worth                value everything at live prices
GET    /api/net-worth/history        daily net-worth snapshots
GET    /api/portfolio?period=        investment gains (since buying, over a period, today) + chart
POST   /api/ai/holdings              the AI on your investments and the market (not saved)
GET    /api/caps?month=              monthly spending caps and how much of each is spent
PUT    /api/caps                     set or remove caps
GET    /api/goals                    savings goals with progress and what each needs per month
POST   /api/goals                    add one
PUT    /api/goals/{id}               change one
DELETE /api/goals/{id}               remove one
POST   /api/ai/savings               the AI on how much you can save (not saved)
GET    /api/savings/one-offs         big one-time deposits left out of monthly income
GET    /api/transfers                moves between your own accounts
POST   /api/transfers                record one (converts currencies at that day's rate if needed)
DELETE /api/transfers/{id}           remove one
GET    /api/fx?currency=             today's exchange rate (units per US dollar)
GET    /api/recurring                recurring rules (rent, subscriptions...)
POST   /api/recurring                create one (past occurrences are filled in)
PATCH  /api/recurring/{id}           pause/resume or change the amount
DELETE /api/recurring/{id}           stop it (past transactions are kept)
GET    /api/settings                 app settings (theme, AI address and model)
PUT    /api/settings                 change settings
PUT    /api/profile                  rename
GET    /api/ai/status                is the PC with Ollama reachable? which models?
GET    /api/ai/reviews/{month}       the last saved AI review for a month
POST   /api/ai/reviews/{month}       generate a new review on the PC
POST   /api/ai/focus                 review only the chosen categories (not saved)
GET    /api/ai/changed               when the data reviews are based on last changed
POST   /api/ai/ask                   answer a question (the model uses lookup tools); optionally a
                                     follow-up on a category analysis or a month's review

Recurring transactions are caught up at the start of *every* request, so
whatever opens the app -- your laptop, your phone, a server that's always on --
sees them as soon as they're due, with no background job needed.
"""

