"""REST API for the web dashboard (Phase 4).

This file is the web version of cli.py: it turns HTTP requests into calls on
the same Store, PriceService, and reports functions, and returns JSON. None of
the business logic lives here.

Run it with `python main.py --web`, then open http://127.0.0.1:8000.
Interactive API docs (generated by FastAPI) are at http://127.0.0.1:8000/docs.

Endpoints
---------
GET    /api/profile                  your name (null for a new user)
POST   /api/profile                  create the profile
GET    /api/summary?month=           spent / income / net for one month
GET    /api/months                   months that have transactions (for pickers)
GET    /api/categories?kind=         category names, most used first
GET    /api/transactions?month=      transactions, newest first
POST   /api/transactions             add one
DELETE /api/transactions/{id}        delete one
GET    /api/transactions.csv         download everything as CSV
POST   /api/import/preview           read a CSV and show what importing would do
POST   /api/import                   import a CSV's new transactions
GET    /api/reports/categories       spending per category (optionally one month)
GET    /api/reports/monthly          last 12 months with how unusual each was
GET    /api/holdings                 your holdings
POST   /api/holdings                 add one
PATCH  /api/holdings/{id}            change quantity or value
DELETE /api/holdings/{id}            remove one
GET    /api/quotes/{symbol}          live price for a ticker (used to check symbols)
GET    /api/net-worth                value everything at live prices
GET    /api/net-worth/history        daily net-worth snapshots
GET    /api/recurring                recurring rules (rent, subscriptions...)
POST   /api/recurring                create one (past occurrences are filled in)
PATCH  /api/recurring/{id}           pause/resume or change the amount
DELETE /api/recurring/{id}           stop it (past transactions are kept)
GET    /api/settings                 app settings (theme, AI address and model)
PUT    /api/settings                 change settings
PUT    /api/profile                  rename
GET    /api/ai/status                is the PC with Ollama reachable? which models?
GET    /api/ai/reviews/{month}       the last saved AI review for a month
POST   /api/ai/reviews/{month}       generate a new review on the PC
POST   /api/ai/ask                   answer a question (the model uses lookup tools)

Recurring transactions are caught up at the start of *every* request, so
whatever opens the app -- your laptop, your phone, a server that's always on --
sees them as soon as they're due, with no background job needed.
"""

